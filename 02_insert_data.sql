SELECT l.l_name as "League Name", t.t_name as "Team Name", m.m_date as "Match Date", m.m_time as "Match Time", s.vs as "VS"
FROM team t
JOIN assemble a ON t.t_id = a.t_id
JOIN organize o ON a.l_id = o.l_id
JOIN league l ON o.l_id = l.l_id
JOIN participate p ON t.t_id = p.t_id
JOIN match_info m ON p.m_id = m.m_id
JOIN schedule s ON p.m_id = s.m_id


OR Use


SELECT l.l_name as "League Name", t.t_name as "Team Name", m.m_date as "Match Date", m.m_time as "Match Time", s.vs as "VS"
FROM team t, assemble a, organize o, league l, participate p, match_info m, schedule s
WHERE t.t_id = a.t_id
    AND a.l_id = o.l_id
    AND o.l_id = l.l_id
    AND t.t_id = p.t_id
    AND p.m_id = m.m_id
    AND p.m_id = s.m_id;



